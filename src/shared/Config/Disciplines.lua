-- Rank index (1-based) a discipline needs before a tier opens.
function Disciplines.tierRankRequirement(discipline, tierId)
	local tier = Disciplines.tiers[tierId]
	local n = #discipline.ranks
	return 1 + math.floor(tier.rankFrac * (n - 1) + 0.5)
end

